function renderAnalyzer() {
  const div = document.getElementById('analyzerContent');
  if (!allResults.length) { div.innerHTML = '<p style="color:#5a9db5;font-size:12px;text-align:center;">Run a scan first.</p>'; return; }

  let html = '';

  // 1. Duplicate detection
  const urlCounts = {};
  allResults.forEach(r => { urlCounts[r.url] = (urlCounts[r.url] || 0) + 1; });
  const dupes = Object.entries(urlCounts).filter(([, c]) => c > 1);
  html += '<div class="analyzer-section"><h4>🔁 Duplicate URLs (' + dupes.length + ')</h4>';
  if (dupes.length) {
    dupes.forEach(([url, count]) => {
      html += '<div class="analyzer-item">× ' + count + ' occurrences — <span style="color:#9de8ff;">' + escapeHTML(url) + '</span></div>';
    });
  } else {
    html += '<div class="analyzer-item" style="color:var(--neon-green);">✅ No duplicate URLs found</div>';
  }
  html += '</div>';

  // 2. Environment variable suggestions
  html += '<div class="analyzer-section"><h4>🔧 Environment Variable Suggestions</h4>';
  const envSuggestions = allResults.map(r => ({
    url: r.url,
    varName: 'URL_' + r.domain.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase()
  }));
  envSuggestions.slice(0, 10).forEach(s => {
    html += '<div class="analyzer-item">'
      + '<span style="color:#7ad3f5;">' + s.varName + '</span> = <span style="color:#9de8ff;">"' + escapeHTML(s.url) + '"</span>'
      + '</div>';
  });
  if (envSuggestions.length > 10) html += '<div class="analyzer-item" style="color:#5a9db5;">… and ' + (envSuggestions.length - 10) + ' more</div>';
  html += '</div>';

  // 3. Sensitive token detection
  const tokenRegex = /[?&](key|token|secret|api_key|apikey|auth|password|passwd|access_token|client_secret)=[^&\s'"]{6,}/gi;
  const tokenMatches = allResults.filter(r => tokenRegex.test(r.url));
  tokenRegex.lastIndex = 0;
  html += '<div class="analyzer-section"><h4>🔑 Sensitive Tokens in URLs (' + tokenMatches.length + ')</h4>';
  if (tokenMatches.length) {
    tokenMatches.forEach(r => {
      html += '<div class="analyzer-item" style="border-color:rgba(255,41,72,0.3);">⚠ Line ' + r.line + ' — <span style="color:var(--neon-red);">' + escapeHTML(r.url) + '</span></div>';
    });
  } else {
    html += '<div class="analyzer-item" style="color:var(--neon-green);">✅ No sensitive tokens detected</div>';
  }
  html += '</div>';

  // 4. Domain frequency
  const domainCount = {};
  allResults.forEach(r => { domainCount[r.domain] = (domainCount[r.domain] || 0) + 1; });
  const topDomains = Object.entries(domainCount).sort((a, b) => b[1] - a[1]).slice(0, 8);
  html += '<div class="analyzer-section"><h4>🌐 Top Domains</h4>';
  topDomains.forEach(([domain, count]) => {
    const pct = Math.round((count / allResults.length) * 100);
    html += '<div class="analyzer-item" style="display:flex;justify-content:space-between;">'
      + '<span>' + escapeHTML(domain) + '</span>'
      + '<span style="color:var(--neon-orange);">' + count + ' URLs (' + pct + '%)</span>'
      + '</div>';
  });
  html += '</div>';

  // 5. Python refactor snippet
  html += '<div class="analyzer-section"><h4>🐍 Python .env Refactor Snippet</h4>';
  html += '<div class="analyzer-item" style="white-space:pre;overflow-x:auto;font-size:10px;line-height:1.6;">';
  html += '# Auto-generated by URL Detector PRO\nimport os\nfrom dotenv import load_dotenv\nload_dotenv()\n\n';
  const seen = new Set();
  allResults.slice(0, 5).forEach(r => {
    if (seen.has(r.url)) return; seen.add(r.url);
    const v = 'URL_' + r.domain.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();
    html += v + ' = os.getenv("' + v + '", "' + escapeHTML(r.url) + '")\n';
  });
  html += '\n# .env file:\n';
  seen.clear();
  allResults.slice(0, 5).forEach(r => {
    if (seen.has(r.url)) return; seen.add(r.url);
    const v = 'URL_' + r.domain.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();
    html += v + '=' + escapeHTML(r.url) + '\n';
  });
  html += '</div></div>';

  div.innerHTML = html;
}
